`timescale 1ns / 1ps
module scope_top
    #(parameter VIDEO_VGA = 0)
    (input wire clk_50m,
     input wire [1 : 0] key_n,
     input wire [11 : 0] adc_data,
     input wire adc_otr,
     output wire adc_clk,
     output wire hdmi_clk_p, hdmi_clk_n,
     output wire [2 : 0] hdmi_data_p, hdmi_data_n,
     inout wire [14 : 0] DDR_addr,
     inout wire [2 : 0] DDR_ba,
     inout wire DDR_cas_n, DDR_ck_n, DDR_ck_p, DDR_cke, DDR_cs_n,
     inout wire [3 : 0] DDR_dm,
     inout wire [31 : 0] DDR_dq,
     inout wire [3 : 0] DDR_dqs_n, DDR_dqs_p,
     inout wire DDR_odt, DDR_ras_n, DDR_reset_n, DDR_we_n,
     inout wire FIXED_IO_ddr_vrn, FIXED_IO_ddr_vrp,
     inout wire [53 : 0] FIXED_IO_mio,
     inout wire FIXED_IO_ps_clk, FIXED_IO_ps_porb, FIXED_IO_ps_srstb);
    wire clk_sys, adc_internal, clk_pixel, clk_serial, locked_adc, locked_video;
    wire [1 : 0] rate;
    scope_clocks #(.VIDEO_VGA(VIDEO_VGA))
        clocks(.clk_50m(clk_50m),
               .rate_sel(rate),
               .clk_sys(clk_sys),
               .clk_adc(adc_internal),
               .clk_pixel(clk_pixel),
               .clk_serial(clk_serial),
               .locked_adc(locked_adc),
               .locked_video(locked_video));
    ODDR #(.DDR_CLK_EDGE("SAME_EDGE"),
           .INIT(1'b0),
           .SRTYPE("ASYNC"))
        adc_forward(.C(adc_internal),
                    .CE(1'b1),
                    .D1(1'b1),
                    .D2(1'b0),
                    .Q(adc_clk),
                    .R(!locked_adc),
                    .S(1'b0));
    wire [23 : 0] rgb;
    wire hs, vs, de, video_rst;
    reset_sync vr(.clk(clk_pixel),
                  .arst(!locked_video),
                  .rst(video_rst));
    scope_core system(.DDR_addr(DDR_addr),
                      .DDR_ba(DDR_ba),
                      .DDR_cas_n(DDR_cas_n),
                      .DDR_ck_n(DDR_ck_n),
                      .DDR_ck_p(DDR_ck_p),
                      .DDR_cke(DDR_cke),
                      .DDR_cs_n(DDR_cs_n),
                      .DDR_dm(DDR_dm),
                      .DDR_dq(DDR_dq),
                      .DDR_dqs_n(DDR_dqs_n),
                      .DDR_dqs_p(DDR_dqs_p),
                      .DDR_odt(DDR_odt),
                      .DDR_ras_n(DDR_ras_n),
                      .DDR_reset_n(DDR_reset_n),
                      .DDR_we_n(DDR_we_n),
                      .FIXED_IO_ddr_vrn(FIXED_IO_ddr_vrn),
                      .FIXED_IO_ddr_vrp(FIXED_IO_ddr_vrp),
                      .FIXED_IO_mio(FIXED_IO_mio),
                      .FIXED_IO_ps_clk(FIXED_IO_ps_clk),
                      .FIXED_IO_ps_porb(FIXED_IO_ps_porb),
                      .FIXED_IO_ps_srstb(FIXED_IO_ps_srstb),
                      .sys_clk(clk_sys),
                      .sys_locked(locked_adc),
                      .sys_reset(!locked_adc),
                      .adc_clk_in(adc_internal),
                      .pixel_clk(clk_pixel),
                      .adc_data(adc_data),
                      .adc_otr(adc_otr),
                      .adc_locked(locked_adc),
                      .video_locked(locked_video),
                      .key_n(key_n),
                      .rate_sel(rate),
                      .rgb(rgb),
                      .hs(hs),
                      .vs(vs),
                      .de(de));
    hdmi_trans video_tx(.clk1x(clk_pixel),
                        .clk5x(clk_serial),
                        .rst(video_rst),
                        .image_r(rgb[23 : 16]),
                        .image_g(rgb[15 : 8]),
                        .image_b(rgb[7 : 0]),
                        .hsync(hs),
                        .vsync(vs),
                        .de(de),
                        .hdmi_tx_clk_p(hdmi_clk_p),
                        .hdmi_tx_clk_n(hdmi_clk_n),
                        .hdmi_tx_chn_r_p(hdmi_data_p[2]),
                        .hdmi_tx_chn_r_n(hdmi_data_n[2]),
                        .hdmi_tx_chn_g_p(hdmi_data_p[1]),
                        .hdmi_tx_chn_g_n(hdmi_data_n[1]),
                        .hdmi_tx_chn_b_p(hdmi_data_p[0]),
                        .hdmi_tx_chn_b_n(hdmi_data_n[0]));
endmodule
